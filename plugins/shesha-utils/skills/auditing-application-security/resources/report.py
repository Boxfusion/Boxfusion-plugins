"""Optional supporting appendix: cross-cutting tables the per-package catalogue does not show.

    python report.py --repo-root . [--run-dir security-audits/YYMMDD-HHMM]

The per-package JSON catalogue from build_catalogs.py is the primary artefact and the
recommendations are written from it. This writes `audit-tables.md`: the whole-application
views that do not belong to any one package - the live security settings, PermissionedObject
coverage by type, the permission-to-role matrix, probe verdict counts, and the surface-versus-
usage summary. Attach it when a reader wants the numbers behind the recommendations.

Tables and counts only. Severity, ownership judgements and prose are the audit's actual work.

Every number here comes from the same cache the catalogue was built from: revision 1 of an
earlier audit reported the orphaned-permission count as 32 in one document and 29 in another
because the two were computed separately.
"""

import argparse
import collections
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from shesha_audit import (ACCESS, Ownership, cache_dir, index_permissioned_objects,  # noqa: E402
                          latest_run_dir, md_table, new_run_dir, permission_to_roles,
                          read_json, resolve_access, unwrap, write_text)


def load(cache):
    def maybe(name):
        p = os.path.join(cache, name)
        return read_json(p) if os.path.isfile(p) and os.path.getsize(p) > 0 else None

    own_raw = maybe("ownership.json") or {"appModules": [], "appUrlSegments": []}
    d = {
        "own": Ownership(own_raw.get("appModules") or [],
                         own_raw.get("appUrlSegments") or [],
                         own_raw.get("appPathPrefixes") or ()),
        "crossref": maybe("crossref.json"),
        "analysis": maybe("form_analysis.json"),
        "svc": unwrap(maybe("po-shesha-webapi.json")) or [],
        "act": unwrap(maybe("po-shesha-webapi-action.json")) or [],
        "forms_po": unwrap(maybe("po-shesha-form.json")) or [],
        "entity_po": unwrap(maybe("po-shesha-entity.json")) or [],
        "entityact_po": unwrap(maybe("po-shesha-entity-action.json")) or [],
        "entityconfigs": unwrap(maybe("entityconfigs.json")) or [],
        "permissions": unwrap(maybe("permissions.json")) or [],
        "roles": unwrap(maybe("roles.json")) or [],
        "security": (maybe("security-settings.json") or {}).get("result") or {},
        "probes": maybe("probe-results.json"),
        "source": maybe("source_scan.json"),
    }
    return d


def permission_usage(d):
    """permission -> number of PermissionedObject records guarding something with it."""
    used = collections.Counter()
    for src in (d["svc"], d["act"], d["forms_po"]):
        for rec in src:
            for perm in (rec.get("actualPermissions") or []):
                used[perm] += 1
    return used


def access_breakdown(recs):
    c = collections.Counter(r.get("actualAccess") for r in recs)
    return [c.get(k, 0) for k in (1, 2, 3, 4, 5)]


def emit_audit_tables(d, out_dir):
    L = []
    w = L.append
    own = d["own"]
    default_access = (d["security"] or {}).get("defaultEndpointAccess")
    w("<!-- generated by resources/report.py - tables only, prose is the model's job -->")
    w("# Audit tables — generated %s" % datetime.date.today().isoformat())
    w("")
    w("## Live security configuration")
    w("")
    sec = d["security"] or {}
    rows = [(k, sec.get(k)) for k in sorted(sec)] if sec else []
    w(md_table(["Setting", "Value"], rows) if rows else "_security-settings.json not collected_")
    w("")
    if default_access is not None:
        w("`defaultEndpointAccess` = **%s (%s)**. This is the `replaceInherited` value for both "
          "`ApiAuthorizationHelper` and `EntityCrudAuthorizationHelper`, so it is the effective "
          "default for every `Inherited` record and for all entity CRUD."
          % (default_access, ACCESS.get(default_access, "?")))
        w("")

    w("## PermissionedObject coverage")
    w("")
    rows = []
    for label, recs in [("Shesha.WebApi", d["svc"]), ("Shesha.WebApi.Action", d["act"]),
                        ("Shesha.Entity", d["entity_po"]),
                        ("Shesha.Entity.Action", d["entityact_po"]),
                        ("Shesha.Form", d["forms_po"])]:
        b = access_breakdown(recs)
        rows.append([("`%s`" % label), len(recs)] + b)
    w(md_table(["Type", "Records", "Disabled", "Inherited", "AnyAuth",
                "RequiresPermissions", "Anonymous"], rows))
    w("")
    empty = [lbl for lbl, recs in [("Shesha.Entity", d["entity_po"]),
                                   ("Shesha.Entity.Action", d["entityact_po"])] if not recs]
    if empty:
        w("> %s hold **zero** records. `EntityPermissionedObjectProvider` is inactive on "
          "Shesha 0.43.x, so entity access resolves entirely through `DefaultEndpointAccess`."
          % " and ".join("`%s`" % e for e in empty))
        w("")

    w("### App-owned versus package")
    w("")
    rows = []
    for label, recs in [("Shesha.WebApi", d["svc"]), ("Shesha.WebApi.Action", d["act"])]:
        for scope in ("app", "package"):
            sel = [r for r in recs
                   if own.of_module(r.get("module")) == scope]
            b = access_breakdown(sel)
            rows.append(["%s — %s" % (label, scope), len(sel)] + b)
    w(md_table(["Scope", "Records", "Disabled", "Inherited", "AnyAuth",
                "RequiresPermissions", "Anonymous"], rows))
    w("")
    app_perm = sum(1 for r in d["svc"] + d["act"]
                   if own.of_module(r.get("module")) == "app" and r.get("actualAccess") == 4)
    if app_perm == 0:
        w("> **No app-owned endpoint requires a permission.** Every `RequiresPermissions` "
          "record belongs to a package.")
        w("")

    w("## Anonymous-resolving endpoints (actualAccess = 5)")
    w("")
    rows = []
    for rec in sorted(d["act"], key=lambda r: r.get("object") or ""):
        if rec.get("actualAccess") == 5:
            rows.append(["`%s`" % rec["object"], rec.get("module") or "—",
                         own.of_module(rec.get("module")),
                         "code (resets on restart)" if rec.get("hardcoded") else "database"])
    w(md_table(["Object", "Module", "Owner", "Source of the setting"], rows))
    w("")
    w("> `hardcoded = code` means the bootstrapper re-seeds `Access=5` from a code attribute on "
      "every restart. A database change to those does not survive; for a package-owned one the "
      "only mitigations are a proxy rule and an upstream request.")
    w("")

    w("## Permission model")
    w("")
    used = permission_usage(d)
    p2r = permission_to_roles(d["roles"])
    allp = sorted({p.get("name") for p in d["permissions"] if p.get("name")})
    rows = [["`%s`" % p, used.get(p, 0),
             ", ".join(p2r.get(p, [])) or "**(no role)**"] for p in allp]
    w(md_table(["Permission", "Records guarded", "Granted to roles"], rows))
    w("")
    orphan = [p for p in allp if not used.get(p)]
    w("**%d of %d permissions guard nothing.**" % (len(orphan), len(allp)))
    w("")
    rows = [[r.get("name", "").strip(), len(r.get("permissions") or []),
             sum(used.get(p, 0) for p in (r.get("permissions") or []))]
            for r in sorted(d["roles"], key=lambda r: (r.get("name") or "").strip())]
    w(md_table(["Role", "Permissions held", "Records reachable beyond AnyAuthenticated"], rows))
    w("")
    noperm = [r for r in d["roles"] if not (r.get("permissions") or [])]
    if noperm:
        w("%d of %d roles hold no permissions at all: %s."
          % (len(noperm), len(d["roles"]),
             ", ".join((r.get("name") or "").strip() for r in noperm)))
        w("")

    if d["probes"]:
        w("## Probe results")
        w("")
        counts = d["probes"].get("counts") or {}
        w(md_table(["Verdict", "Count"], sorted(counts.items())))
        w("")
        rows = []
        for r in d["probes"]["results"]:
            if r["verdict"] in ("OPEN", "REACHED", "NOT-FOUND", "INCONCLUSIVE", "JUDGEMENT"):
                rows.append([r["verdict"], r["method"], "`%s`" % r["path"],
                             "auth" if r["authenticated"] else "anon", r["status"],
                             r.get("severityIfOpen") or "—",
                             ACCESS.get(r.get("recordAccess"), "—")])
        w(md_table(["Verdict", "Method", "Path", "As", "HTTP", "Severity if open",
                    "Record access"], rows))
        w("")
        w("> `NOT-FOUND` and `INCONCLUSIVE` are **not** passes. Record each one in Appendix B.")
        w("")

    if d["crossref"]:
        s = d["crossref"]["summary"]
        w("## Surface and usage")
        w("")
        w(md_table(["Measure", "Value"], [[k, s[k]] for k in sorted(s)]))
        w("")
        if s.get("opaqueRefs"):
            w("**Confidence: reduced.** %d opaque references across %d forms could reach any "
              "endpoint. The unreferenced list is a review queue, not an apply list."
              % (s["opaqueRefs"], s["opaqueForms"]))
            w("")
        rows = [["`%s`" % p, ",".join(m)]
                for p, m, o in d["crossref"]["unreferenced"] if o == "app"]
        w("### App-owned unreferenced endpoints (%d)" % len(rows))
        w("")
        w(md_table(["Endpoint", "Methods"], rows))
        w("")
        rows = [["`%s`" % b, n, o] for b, n, u, o in d["crossref"]["fullyUnusedEntities"]]
        w("### Dynamic entities with no referenced action (%d)" % len(rows))
        w("")
        w(md_table(["Dynamic CRUD base", "Actions", "Owner"], rows))
        w("")

    if d["entityconfigs"]:
        w("## Entity configuration")
        w("")
        app = [e for e in d["entityconfigs"]
               if own.of_module(e.get("module")) == "app"]
        gen = sum(1 for e in app if e.get("generateAppService"))
        live_bases = set()
        if d["crossref"]:
            live_bases = set(d["crossref"].get("entActions") or {})
        w(md_table(["Measure", "Value"], [
            ["EntityConfig rows", len(d["entityconfigs"])],
            ["with generateAppService = true",
             sum(1 for e in d["entityconfigs"] if e.get("generateAppService"))],
            ["app-owned rows", len(app)],
            ["app-owned with generateAppService = true", gen],
            ["entities with a live dynamic CRUD route", len(live_bases)],
        ]))
        w("")

    path = os.path.join(out_dir, "audit-tables.md")
    write_text(path, "\n".join(L) + "\n")
    print("written %s (%d lines)" % (path, len(L)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-root", default=".")
    ap.add_argument("--cache", default=None)
    ap.add_argument("--url", default="http://localhost:21021")
    ap.add_argument("--out-dir", default=None,
                    help="defaults to a new security-audits/YYMMDD-HHMM directory")
    ap.add_argument("--run-dir", default=None,
                    help="write into this existing run directory instead of a new one")
    args = ap.parse_args()

    cache = args.cache or cache_dir(args.repo_root, args.url)
    d = load(cache)
    if not d["svc"]:
        print("No PermissionedObject data in %s. Run collect.py first." % cache,
              file=sys.stderr)
        return 2

    out_dir = args.out_dir or args.run_dir or new_run_dir(args.repo_root)
    emit_audit_tables(d, out_dir)
    print("run directory: %s" % out_dir)
    previous = latest_run_dir(args.repo_root, before=out_dir)
    if previous:
        print("previous run:  %s  <- the report's comparison section comes from here"
              % previous)
    else:
        print("previous run:  none - this is the baseline audit")
    return 0


if __name__ == "__main__":
    sys.exit(main())
